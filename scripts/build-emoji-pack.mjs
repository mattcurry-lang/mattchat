// scripts/build-emoji-pack.mjs
// Regenerates frontend/src/components/emojiPackData.js from the official Unicode
// emoji data (CLDR, via the `emojibase-data` package).
//
//   npm i -D emojibase-data
//   node scripts/build-emoji-pack.mjs
//
// MAX_VERSION is the newest Unicode emoji version included. Newer emojis show as
// empty boxes on devices whose system emoji font is older, so the default stays
// at 13.1 (2020). Raise it once you are happy to drop older phones/PCs.

import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'

const require = createRequire(import.meta.url)
const data = require('emojibase-data/en/data.json')
const messages = require('emojibase-data/en/messages.json')

const MAX_VERSION = 13.1

// Our own tidy categories, in display order, mapped from the Unicode group keys.
const GROUPS = [
  { id: 'smileys',    label: 'Smileys & Emotion', icon: '😀', key: 'smileys-emotion' },
  { id: 'people',     label: 'People & Body',     icon: '👋', key: 'people-body' },
  { id: 'animals',    label: 'Animals & Nature',  icon: '🐶', key: 'animals-nature' },
  { id: 'food',       label: 'Food & Drink',      icon: '🍕', key: 'food-drink' },
  { id: 'travel',     label: 'Travel & Places',   icon: '✈️', key: 'travel-places' },
  { id: 'activities', label: 'Activities',        icon: '⚽', key: 'activities' },
  { id: 'objects',    label: 'Objects',           icon: '💡', key: 'objects' },
  { id: 'symbols',    label: 'Symbols',           icon: '❤️', key: 'symbols' },
  { id: 'flags',      label: 'Flags',             icon: '🏁', key: 'flags' },
]
const keyByOrder = new Map(messages.groups.map((g) => [g.order, g.key]))

// Chat shorthand people actually type. Added to the search text of these emojis.
const ALIASES = {
  '😂': 'lol lmao haha laughing', '🤣': 'lol lmao rofl haha', '😍': 'love crush heart eyes', '🥰': 'love cute adore',
  '😘': 'kiss muah', '😭': 'crying sob sad', '😱': 'omg shocked scared', '😮': 'omg wow', '🤔': 'hmm thinking',
  '🙏': 'thanks thank you pray please', '👍': 'ok yes like good', '👎': 'no dislike bad', '👌': 'ok perfect',
  '🔥': 'fire lit hot', '💯': 'hundred perfect 100', '❤️': 'love heart', '💔': 'heartbreak broken heart sad',
  '😴': 'sleep sleepy tired zzz', '🎉': 'party congrats celebrate', '🥳': 'party birthday celebrate', '😎': 'cool sunglasses',
  '😡': 'angry mad', '🤝': 'deal handshake agreement', '👏': 'clap well done bravo', '💪': 'strong muscle flex gym',
  '🙌': 'praise hooray celebrate', '😅': 'nervous relief phew', '🥺': 'please pleading puppy eyes', '🤷': 'idk shrug whatever',
}

const norm = (s) => s.replace(/\uFE0F/g, '')
const entries = []
const seen = new Set()

for (const e of data.slice().sort((a, b) => a.order - b.order)) {
  if (e.version > MAX_VERSION) continue
  const groupKey = keyByOrder.get(e.group)
  const gi = GROUPS.findIndex((g) => g.key === groupKey)
  if (gi === -1) continue                       // drops the "component" group (skin swatches, hair parts)
  if (seen.has(norm(e.emoji))) continue         // never list an emoji twice
  seen.add(norm(e.emoji))

  // Skin tone variants: only simple single-tone ones, in tone order 1..5
  let skins = null
  if (e.skins?.length) {
    const byTone = {}
    for (const s of e.skins) if (typeof s.tone === 'number' && s.version <= MAX_VERSION) byTone[s.tone] = s.emoji
    const ordered = [1, 2, 3, 4, 5].map((t) => byTone[t])
    if (ordered.every(Boolean)) skins = ordered
  }

  const tags = [...(e.tags || []), ALIASES[e.emoji] || ''].join(' ').trim()
  entries.push(skins ? [e.emoji, e.label, tags, gi, skins] : [e.emoji, e.label, tags, gi])
}

const out =
  '// GENERATED by scripts/build-emoji-pack.mjs from Unicode CLDR data. Do not edit by hand.\n' +
  `// ${entries.length} emojis, Unicode emoji version <= ${MAX_VERSION}. Format: [emoji, name, keywords, groupIndex, skinTones?]\n` +
  `export const GROUPS = ${JSON.stringify(GROUPS.map(({ id, label, icon }) => ({ id, label, icon })))}\n` +
  `export const EMOJIS = ${JSON.stringify(entries)}\n`

writeFileSync(process.argv[2] || 'emojiPackData.js', out)
console.log(`wrote ${entries.length} emojis (${(out.length / 1024).toFixed(0)} KB)`)
